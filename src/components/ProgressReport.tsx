import { useState } from 'react';
import { useAppStore } from '@/state/store';
import { FileText, ChevronDown, ChevronUp, Sprout, AlertTriangle, Lightbulb, Heart } from 'lucide-react';
import { fetchReport } from '@/services/harnessService';

interface ReportData { summary: string; strengths: string[]; areasToImprove: string[]; parentTips: string[]; overallGrade: string; treeHealth: number; }

export default function ProgressReport() {
  const progress = useAppStore(s => s.progress);
  const [report, setReport] = useState<ReportData | null>(null);
  const [loading, setLoading] = useState(false);
  const [expanded, setExpanded] = useState(false);

  const generate = async () => {
    setLoading(true);
    try {
      const data = await fetchReport({
        completedChapters: Object.keys(progress.chaptersCompleted).filter(k => progress.chaptersCompleted[k]),
        quizResults: progress.quizResults,
        streakDays: progress.streakDays || 0,
        longestStreak: progress.longestStreak || 0,
        coins: progress.coins,
        notesCount: 0,
        achievementsUnlocked: Object.keys(progress.achievementsUnlocked).length,
      });
      setReport(data);
      setExpanded(true);
    } catch { setReport(null); }
    finally { setLoading(false); }
  };

  return (
    <div className="bg-gradient-to-r from-amber-950/50 to-orange-950/50 border border-amber-500/30 rounded-xl overflow-hidden">
      <button onClick={() => report ? setExpanded(!expanded) : generate()} disabled={loading}
        className="w-full flex items-center justify-between p-6 hover:bg-amber-900/10 transition-colors">
        <div className="flex items-center gap-3">
          <FileText className="text-amber-400" size={20} />
          <div className="text-left">
            <h3 className="text-lg font-bold text-slate-100">Parent / Teacher Report</h3>
            <p className="text-sm text-slate-400">{report ? `Tree health: ${report.treeHealth}/100 — ${report.overallGrade}` : 'AI-generated progress assessment'}</p>
          </div>
        </div>
        {loading ? <span className="text-amber-400 animate-pulse text-sm">Generating...</span>
          : report ? (expanded ? <ChevronUp className="text-slate-400" size={20} /> : <ChevronDown className="text-slate-400" size={20} />)
          : <span className="text-amber-400 text-sm font-medium">Generate →</span>}
      </button>
      {report && expanded && (
        <div className="px-6 pb-6 space-y-5 border-t border-amber-500/20 pt-4">
          <div>
            <div className="flex justify-between text-sm mb-2"><span className="text-slate-300">Money Tree health</span><span className="font-bold text-amber-300">{report.treeHealth}/100</span></div>
            <div className="w-full bg-slate-700 rounded-full h-3">
              <div className={`h-full rounded-full transition-all duration-700 ${report.treeHealth >= 70 ? 'bg-green-500' : report.treeHealth >= 40 ? 'bg-amber-500' : 'bg-red-500'}`} style={{ width: `${report.treeHealth}%` }} />
            </div>
          </div>
          <p className="text-sm text-slate-300 bg-slate-800/30 p-3 rounded-lg">{report.summary}</p>
          <div><h4 className="text-sm font-semibold text-green-300 flex items-center gap-2 mb-2"><Sprout size={14} /> Strengths</h4>{report.strengths.map((s, i) => <p key={i} className="text-sm text-slate-300 pl-5">• {s}</p>)}</div>
          <div><h4 className="text-sm font-semibold text-amber-300 flex items-center gap-2 mb-2"><AlertTriangle size={14} /> Areas to strengthen</h4>{report.areasToImprove.map((s, i) => <p key={i} className="text-sm text-slate-300 pl-5">• {s}</p>)}</div>
          <div><h4 className="text-sm font-semibold text-purple-300 flex items-center gap-2 mb-2"><Lightbulb size={14} /> Tips for parents</h4>{report.parentTips.map((s, i) => <p key={i} className="text-sm text-slate-300 pl-5">• {s}</p>)}</div>
          <p className="text-xs text-slate-500 text-center flex items-center justify-center gap-1"><Heart size={10} /> Generated by the Money Tree AI Harness</p>
        </div>
      )}
    </div>
  );
}
